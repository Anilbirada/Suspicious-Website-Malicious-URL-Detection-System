    await waitFor(() => {
      expect(screen.getByTestId('model-loaded-indicator')).toHaveTextContent('Yes — Active');
    });

    // Navigate to History empty state
    await userEvent.click(screen.getByRole('button', { name: /Analysis History/i }));
    await waitFor(() => {
      expect(screen.getByTestId('empty-history-state')).toBeInTheDocument();
    });

    // Navigate to About & Credits and verify 'Developer: Anil Biradar'
